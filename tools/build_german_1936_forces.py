"""Build NWW's peacetime imperial forces using installed DLC equipment patterns."""
from collections import Counter
import copy
import json
from pathlib import Path

from hoi4_script import dump, one, parse, read, values, walk

ROOT = Path(__file__).resolve().parents[1]
GAME = Path('D:/Steam/steamapps/common/Hearts of Iron IV')


def save(relative, doc):
    path = ROOT / relative
    path.parent.mkdir(parents=True, exist_ok=True)
    text = dump(doc)
    for carrier in ['SMS Graf Zeppelin', 'SMS Deutschland', 'SMS Europa']:
        text = text.replace('\t' + carrier + ' = {', '\t"' + carrier + '" = {')
    path.write_text('# NWW imperial 1936 setup; generated by tools/build_german_1936_forces.py.\n'
                    + text + '\n', encoding='utf-8', newline='\n')


def setv(node, key, value):
    node[:] = [entry for entry in node if entry[0] != key]
    node.append((key, value, '='))


def effective(folder):
    paths = {p.name: p for p in (GAME / folder).glob('*.txt')}
    paths.update({p.name: p for p in (ROOT / folder).glob('*.txt')})
    return paths.values()


def main():
    states, provinces = {}, {}
    for path in effective('history/states'):
        state = one(read(path), 'state')
        sid = one(state, 'id')
        states[sid] = state
        for _, pid, _ in one(state, 'provinces', []):
            provinces[pid] = (sid, one(one(state, 'history', []), 'owner'))
    imperial = json.loads((ROOT / 'docs/GER_overseas_setup.json').read_text())
    overseas = {str(entry['state']) for entry in imperial['territories']}
    centres = []
    for sid, state in states.items():
        history = one(state, 'history', [])
        if one(history, 'owner') != 'GER' or sid in overseas:
            continue
        vps = []
        for block in values(history, 'victory_points'):
            items = [v for _, v, _ in block]
            vps.extend((int(score), pid) for pid, score in zip(items[::2], items[1::2]))
        if vps:
            centres.append(sorted(vps, reverse=True))
    centres.sort(key=lambda group: -group[0][0])
    mainland = [group[i][1] for i in range(max(map(len, centres))) for group in centres if i < len(group)]
    # Ports actually owned by Germany; no foreign basing or colonial cores.
    colonies = ['2196', '6039', '1951', '10000', '3995', '2489', '12240', '4357']
    for pid in colonies:
        assert provinces[pid][1] == 'GER'
    base = read(ROOT / 'history/units/GER_1936_nsb.txt')
    templates = {one(t, 'name'): t for t in values(base, 'division_template')}
    colonial = copy.deepcopy(templates['Infanterie-Division'])
    setv(colonial, 'name', 'Schutztruppe')
    setv(colonial, 'regiments', one(templates['Gebirgs-Brigade'], 'regiments'))
    setv(colonial, 'regiments', [(('infantry' if k == 'mountaineers' else k), v, o)
                               for k, v, o in one(colonial, 'regiments')])
    setv(colonial, 'support', parse('engineer = { x = 0 y = 0 }'))
    colonial[:] = [entry for entry in colonial if entry[0] != 'division_names_group']
    templates['Schutztruppe'] = colonial
    divisions = []
    composition = [('Kaiser-Infanterie', 60), ('Infanterie-Division (mot.)', 6),
                   ('Panzer-Regiment', 4), ('Gebirgs-Brigade', 4), ('Kavallerie-Brigade', 2),
                   ('Schutztruppe', 8)]
    for template, count in composition:
        for number in range(1, count + 1):
            pid = colonies[number - 1] if template == 'Schutztruppe' else mainland[len(divisions) % len(mainland)]
            if template == 'Gebirgs-Brigade':
                # Bavarian and Silesian mountain districts, still inside GER.
                pid = ['692', '9515', '9572', '6570'][number - 1]
                if provinces.get(pid, (None, None))[1] != 'GER':
                    pid = mainland[len(divisions) % len(mainland)]
            divisions.append(('division', parse(f'name = "{number}. {template}" location = {pid} '
                                                f'division_template = "{template}" '
                                                'start_equipment_factor = 1 start_experience_factor = 0.20'), '='))
    for suffix in ['', '_nsb']:
        source = ROOT / f'history/units/GER_1936{suffix}.txt'
        if not source.exists():
            source = GAME / f'history/units/GER_1936{suffix}.txt'
        doc = read(source)
        doc = [entry for entry in doc if entry[0] not in {'units', 'division_template'}]
        doc = [('division_template', copy.deepcopy(t), '=') for t in templates.values()] + [('units', divisions, '=')] + doc
        save(f'history/units/GER_1936{suffix}.txt', doc)

    eng = read(ROOT / 'history/countries/ENG - Britain.txt')
    ger = read(ROOT / 'history/countries/GER - Germany.txt')
    initial_eng = [entry for entry in eng if not (entry[0] and entry[0][0].isdigit())]
    initial_ger = [entry for entry in ger if not (entry[0] and entry[0][0].isdigit())]
    native_variants = {one(v, 'name'): v for k, v, _ in walk(initial_eng) if k == 'create_equipment_variant'}
    german_variants = {one(v, 'name'): v for k, v, _ in walk(initial_ger) if k == 'create_equipment_variant'}
    effect = parse('set_technology = { electronic_mechanical_engineering = 1 radio = 1 '
                   'basic_machine_tools = 1 construction1 = 1 concentrated_industry = 1 '
                   'excavation1 = 1 support_weapons = 1 tech_logistics_company = 1 tech_field_hospital = 1 }')
    naval = parse('set_technology = { early_ship_hull_carrier = 1 basic_ship_hull_carrier = 1 '
                  'basic_fire_control_system = 1 basic_heavy_armor_scheme = 1 smoke_generator = 1 }')
    specs = [('NWW Kaiser', 'Revenge Class'), ('NWW Koenig', 'Queen Elizabeth Class'),
             ('NWW Bayern', 'Queen Elizabeth Class'), ('NWW Preussen', 'Bismarck'),
             ('NWW Derfflinger', 'Renown Class'), ('NWW Admiral', 'County Class'),
             ('NWW Kreuzer', 'Leipzig'), ('NWW Europa', 'Courageous Class'),
             ('NWW Flugzeugtraeger', 'Ark Royal Class')]
    designs = {}
    for name, source in specs:
        variant = copy.deepcopy(german_variants.get(source, native_variants.get(source)))
        variant[:] = [entry for entry in variant if entry[0] not in
                      {'name_group', 'design_team', 'optional_assets', 'obsolete', 'icon', 'parent_version'}]
        setv(variant, 'name', name)
        modules = one(variant, 'modules')
        # Early AA, conventional secondary batteries and optical fire control.
        for slot, module, op in list(modules):
            if module.startswith('dp_ship_secondaries'):
                setv(modules, slot, 'ship_secondaries_1')
            elif module == 'ship_anti_air_2':
                setv(modules, slot, 'ship_anti_air_1')
        if name == 'NWW Preussen':
            setv(modules, 'fixed_ship_armor_slot', 'ship_armor_bb_1')
        if name == 'NWW Flugzeugtraeger':
            setv(modules, 'fixed_ship_engine_slot', 'carrier_ship_engine_1')
        designs[name] = variant
        naval.append(('create_equipment_variant', variant, '='))
    effect.append(('if', [('limit', parse('has_dlc = "Man the Guns"'), '=')] + naval +
                   [('else', parse('set_technology = { early_carrier = 1 basic_carrier = 1 basic_battlecruiser = 1 } '
                                   'create_equipment_variant = { name = "NWW Europa Legacy" type = carrier_1 '
                                   'upgrades = { ship_deckspace_upgrade = 2 } }'), '=')], '='))
    air_designs = [
        ('NWW Jagdflugzeug 36', 'small_plane_airframe_1', 'light_mg_4x', 'engine_2_1x'),
        ('NWW Sturzkampfflugzeug 36', 'small_plane_cas_airframe_1', 'bomb_locks', 'engine_2_1x'),
        ('NWW Kampfflugzeug 36', 'medium_plane_airframe_1', 'medium_bomb_bay', 'engine_2_2x'),
        ('NWW Seeaufklaerer 36', 'small_plane_naval_bomber_airframe_1', 'torpedo_mounting', 'engine_2_1x'),
        ('NWW Fernbomber 34', 'large_plane_airframe_0', 'large_bomb_bay', 'engine_1_4x'),
        ('NWW Traegerjaeger 36', 'cv_small_plane_airframe_1', 'light_mg_4x', 'engine_2_1x'),
        ('NWW Traegertorpedoflugzeug 36', 'cv_small_plane_naval_bomber_airframe_1', 'torpedo_mounting', 'engine_2_1x'),
    ]
    bba = parse('set_technology = { basic_small_airframe = 1 basic_medium_airframe = 1 air_torpedoe_1 = 1 }')
    for name, equipment, weapon, engine in air_designs:
        bba.append(('create_equipment_variant', parse(f'name = "{name}" type = {equipment} '
                    f'modules = {{ fixed_main_weapon_slot = {weapon} engine_type_slot = {engine} }}'), '='))
    effect.append(('if', [('limit', parse('has_dlc = "By Blood Alone"'), '=')] + bba +
                   [('else', parse('set_technology = { cv_early_fighter = 1 cv_fighter1 = 1 cv_naval_bomber1 = 1 }'), '=')], '='))
    save('common/scripted_effects/GER_military_setup_effects.txt', [('GER_nww_1936_military_technology', effect, '=')])

    # Separate regional fleets and screened carrier task forces, same roster with/without MTG.
    fleet_plan = [
        ('Hochseeflotte', '6389', [
            ('I. Linienschiffgeschwader', [('battleship', 'NWW Koenig', ['Koenig', 'Grosser Kurfuerst', 'Markgraf', 'Kronprinz']), ('light_cruiser', 'NWW Kreuzer', ['Koeln', 'Karlsruhe']), ('destroyer', 'Type 24', 8)]),
            ('II. Linienschiffgeschwader', [('battleship', 'NWW Bayern', ['Bayern', 'Baden', 'Sachsen', 'Wuerttemberg']), ('light_cruiser', 'NWW Kreuzer', ['Nuernberg', 'Leipzig']), ('destroyer', 'Zerstörer 1934', 8)]),
            ('III. Linienschiffgeschwader', [('battleship', 'NWW Preussen', ['Preussen', 'Hannover']), ('light_cruiser', 'NWW Kreuzer', ['Bremen', 'Hamburg']), ('destroyer', 'Zerstörer 1934', 4)]),
            ('Aufklaerungsgruppe', [('battle_cruiser', 'NWW Derfflinger', ['Derfflinger', 'Luetzow', 'Hindenburg', 'Fuerst Bismarck']), ('light_cruiser', 'NWW Kreuzer', ['Stuttgart', 'Rostock']), ('destroyer', 'Zerstörer 1934', 8)]),
            ('I. Traegergruppe', [('carrier', 'NWW Flugzeugtraeger', ['Graf Zeppelin']), ('heavy_cruiser', 'NWW Admiral', ['Admiral Hipper', 'Prinz Eugen']), ('light_cruiser', 'NWW Kreuzer', ['Magdeburg', 'Stralsund']), ('destroyer', 'Zerstörer 1934', 8)]),
            ('II. Traegergruppe', [('carrier', 'NWW Flugzeugtraeger', ['Deutschland']), ('heavy_cruiser', 'NWW Admiral', ['Roon', 'Yorck']), ('light_cruiser', 'NWW Kreuzer', ['Augsburg', 'Mainz']), ('destroyer', 'Zerstörer 1934', 8)]),
        ]),
        ('Ostseeflotte', '6332', [
            ('Baltisches Geschwader', [('battleship', 'NWW Kaiser', ['Kaiser', 'Friedrich der Grosse', 'Koenig Albert', 'Prinzregent Luitpold']), ('heavy_cruiser', 'NWW Admiral', ['Blücher', 'Seydlitz']), ('light_cruiser', 'NWW Kreuzer', ['Koenigsberg', 'Danzig', 'Stettin', 'Luebeck']), ('destroyer', 'Type 24', 12)]),
        ]),
        ('Ostasiengeschwader', '10000', [
            ('III. Traegergruppe', [('carrier', 'NWW Europa', ['Europa']), ('heavy_cruiser', 'NWW Admiral', ['Scharnhorst', 'Gneisenau']), ('light_cruiser', 'NWW Kreuzer', ['Emden', 'Potsdam']), ('destroyer', 'Zerstörer 1934', 8)]),
            ('Pazifikstation', [('light_cruiser', 'NWW Kreuzer', ['Dresden', 'Karlsbad']), ('destroyer', 'Type 24', 4)]),
        ]),
        ('Afrikageschwader', '2196', [
            ('Ostafrikanische Station', [('heavy_cruiser', 'NWW Admiral', ['Friedrich Carl', 'Prinz Adalbert']), ('light_cruiser', 'NWW Kreuzer', ['Koenigswoerth', 'Daressalam']), ('destroyer', 'Zerstörer 1934', 4)]),
            ('Westafrikanische Station', [('light_cruiser', 'NWW Kreuzer', ['Windhuk', 'Duala'])]),
        ]),
        ('Unterseebootsflotte', '6389', [
            ('I. Unterseebootsflottille', [('submarine', 'Type II', 16)]),
            ('II. Unterseebootsflottille', [('submarine', 'Type VII', 20)]),
        ]),
    ]
    totals = Counter()
    for mtg in [True, False]:
        fleets = []
        serials = Counter()
        for fleet_name, port, groups in fleet_plan:
            fleet = parse(f'name = "{fleet_name}" naval_base = {port}')
            for group_name, entries in groups:
                tf = parse(f'name = "{group_name}" location = {port}')
                for kind, design, names in entries:
                    if isinstance(names, int):
                        prefix = 'U-' if kind == 'submarine' else 'V-' if design == 'Type 24' else 'Z-'
                        names = [prefix + str(serials[prefix] + i) for i in range(1, names + 1)]
                        serials[prefix] += len(names)
                    for name in names:
                        if mtg:
                            equipment_type = one(designs[design], 'type') if design in designs else one(german_variants[design], 'type')
                            version = f'version_name = "{design}"'
                        else:
                            equipment_type = {'battleship': 'battleship_1', 'battle_cruiser': 'battle_cruiser_1',
                                              'carrier': 'carrier_2', 'heavy_cruiser': 'heavy_cruiser_1',
                                              'light_cruiser': 'light_cruiser_1', 'destroyer': 'destroyer_1',
                                              'submarine': 'submarine_1'}[kind]
                            if design in {'NWW Preussen', 'Zerstörer 1934', 'Type VII'}:
                                equipment_type = {'NWW Preussen': 'battleship_2', 'Zerstörer 1934': 'destroyer_2', 'Type VII': 'submarine_2'}[design]
                            version = ''
                            if design == 'NWW Europa':
                                equipment_type = 'carrier_1'
                                version = 'version_name = "NWW Europa Legacy"'
                        ship_name = name if kind in {'destroyer', 'submarine'} else 'SMS ' + name
                        tf.append(('ship', parse(f'name = "{ship_name}" definition = {kind} start_experience_factor = 0.20 '
                                   f'equipment = {{ {equipment_type} = {{ amount = 1 owner = GER {version} }} }}'), '='))
                        if mtg:
                            totals[kind] += 1
                fleet.append(('task_force', tf, '='))
            fleets.append(('fleet', fleet, '='))
        save('history/units/GER_1936_naval_mtg.txt' if mtg else 'history/units/GER_1936_naval.txt', [('units', fleets, '=')])

    for bba_enabled in [True, False]:
        wings = []
        # Wing size and distribution respect existing state air-base capacities.
        distribution = [('64', 0, 300), ('66', 0, 300), ('57', 0, 300),
                        ('51', 1, 120), ('56', 1, 120), ('66', 2, 240), ('763', 2, 240),
                        ('58', 3, 120), ('743', 3, 60), ('64', 4, 120)]
        legacy_types = ['fighter_equipment_1', 'CAS_equipment_1', 'tac_bomber_equipment_1',
                        'nav_bomber_equipment_1', 'strat_bomber_equipment_1',
                        'cv_fighter_equipment_1', 'cv_nav_bomber_equipment_1']
        for sid, index, amount in distribution:
            name, equipment, _, _ = air_designs[index]
            if not bba_enabled:
                equipment = legacy_types[index]
            blocks = []
            for n in range(0, amount, 60):
                version = f'version_name = "{name}"' if bba_enabled else ''
                blocks.append((equipment, parse(f'owner = GER amount = {min(60, amount-n)} {version}'), '='))
            wings.append((sid, blocks, '='))
        wings.append(('64', parse('transport_plane_equipment_1 = { owner = GER amount = 60 }'), '='))
        for carrier in ['SMS Graf Zeppelin', 'SMS Deutschland', 'SMS Europa']:
            blocks = []
            for index in [5, 6]:
                name, equipment, _, _ = air_designs[index]
                if not bba_enabled:
                    equipment = legacy_types[index]
                version = f'version_name = "{name}"' if bba_enabled else ''
                blocks.append((equipment, parse(f'owner = GER amount = 30 {version}'), '='))
            wings.append((carrier, blocks, '='))
        filename = f'history/units/GER_1936_air_{"bba" if bba_enabled else "legacy"}.txt'
        production = one(read(GAME / filename), 'instant_effect', [])
        save(filename, [('air_wings', wings, '='), ('instant_effect', production, '=')])
    path = ROOT / 'history/countries/GER - Germany.txt'
    text = path.read_text(encoding='utf-8-sig')
    call = 'GER_nww_1936_military_technology = yes'
    text = text.replace('\n' + call, '')
    # Default hull/airframe research must precede custom variant creation.
    text = text.replace('nww_GER_disable_mefo = yes', call + '\nnww_GER_disable_mefo = yes', 1)
    text = text.replace('set_grand_doctrine = new_convoy_raiding', 'set_grand_doctrine = new_fleet_in_being')
    text = text.replace('starting_train_buffer = 2', 'starting_train_buffer = 4')
    path.write_text(text, encoding='utf-8', newline='\n')
    report = {'divisions': dict(composition), 'total_divisions': len(divisions),
              'ships': dict(totals), 'total_ships': sum(totals.values()),
              'aircraft': {'land_based': 1980, 'carrier_based': 180, 'total': 2160},
              'carrier_names': ['SMS Graf Zeppelin', 'SMS Deutschland', 'SMS Europa'],
              'colonial_garrisons': colonies}
    (ROOT / 'docs/GER_1936_forces.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
