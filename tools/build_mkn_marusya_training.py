"""Build Marusya's hidden urban-training tech from the target version's land units.

Uses the GoE urban_training_tech pattern. Apply to combat-width battalions only:
support-company terrain modifiers are additive, so granting them again would stack.
"""
import argparse
import json
from pathlib import Path

from hoi4_script import read, one, values

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--game', type=Path, default=Path.home()/'.local/share/Steam/steamapps/common/Hearts of Iron IV')
    game = parser.parse_args().game
    if not game.is_dir(): parser.error(f'Installed HOI4 directory does not exist: {game}')
    effective = {p.name:p for p in (game/'common/units').glob('*.txt')}
    effective.update({p.name:p for p in (ROOT/'common/units').glob('*.txt')})
    units = {}
    for path in effective.values():
        for token, node, op in one(read(path),'sub_units',[]):
            categories = {v for k,v,o in one(node,'categories',[])}
            if 'category_army' in categories and float(one(node,'combat_width','0')) > 0:
                units[token] = path.name
    assert {'infantry','cavalry','artillery_brigade'} <= units.keys()
    lines = ['# Owner: MKN. Generated by tools/build_mkn_marusya_training.py.',
             '# Native pattern: technologies/infantry.txt, urban_training_tech (GoE).',
             'technologies = {', '\tMKN_marusya_assault_training = {',
             '\t\tresearch_cost = 1', '\t\tallow = { always = no }',
             '\t\tenable_equipments = {}']
    for token in sorted(units):
        lines.append(f'\t\t{token} = {{ urban = {{ attack = 0.15 }} }}')
    lines.extend(['\t}', '}'])
    destination = ROOT/'common/technologies/MKN_technologies.txt'
    destination.parent.mkdir(parents=True,exist_ok=True)
    destination.write_text('\n'.join(lines)+'\n')
    (ROOT/'docs/MKN_marusya_training.json').write_text(json.dumps(units,indent=2,sort_keys=True)+'\n')
    print(f'PASS: Marusya urban training covers {len(units)} native combat battalions; no additive support stacking')


if __name__ == '__main__':
    main()
